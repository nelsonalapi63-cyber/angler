#!/usr/bin/env node
/* Builds the browser data globals from data/*.json:
 *   boot.js     -> window.FATHOM_BOOT: today's and tomorrow's prompts (plus the tutorial's), the entities they use,
 *                  the packs, those two schedule days and the taxa groups those prompts need — enough to start the
 *                  Daily Dive at once. The page loads this first; the full bank arrives in the background.
 *   entities.js -> window.FATHOM_ENTITIES  (object keyed by id; `art: true` where data/illustrations/<id>.svg exists)
 *   prompts.js  -> window.FATHOM_PROMPTS (array), window.FATHOM_PACKS (array), window.FATHOM_SCHEDULE (day -> ids),
 *                  window.FATHOM_DATA_VERSION (hash shared with the server)
 *   taxa.js     -> window.FATHOM_TAXA (group -> species names; the safety net for species prompts)
 * It also extends data/schedule.json: days up to and including today stay exactly as they were (so the archive and
 * the server agree with what people played); every later day is regenerated from the current bank, SCHEDULE_DAYS_AHEAD out.
 * It also writes 404.html's redirect target, robots.txt and sitemap.xml from data/site.json, and with --dist copies
 * the deployable site into dist/ (what the GitHub Pages workflow uploads) with a CNAME file when siteUrl is set.
 * Usage: node build.js [--partial] [--dist]   (--partial skips the 120-prompt floor while the bank is still growing)
 */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { validateData } = require('./tools/validate-data.js');
const dive = require('./shared/dive.js');

const SCHEDULE_DAYS_AHEAD = 400;
const BOOT_DAYS = 1;                                    // today travels in boot.js; tomorrow comes with the full bank (cached offline by the service worker)
const TUTORIAL_PROMPT_IDS = ['shark-species', 'whale-species', 'tide-pool'];   // must match game.js

const ROOT = __dirname;
const partial = process.argv.includes('--partial');
const wantDist = process.argv.includes('--dist');
const site = fs.existsSync(path.join(ROOT, 'data', 'site.json')) ? JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'site.json'), 'utf8')) : { siteUrl: '' };
const SITE_URL = String(site.siteUrl || '').replace(/\/+$/, '');
const res = validateData({ allowPartial: partial });
for (const e of res.errors) console.error('ERROR: ' + e);
if (!res.ok) { console.error('build aborted: data does not validate'); process.exit(1); }

const read = (f) => JSON.parse(fs.readFileSync(path.join(ROOT, 'data', f), 'utf8'));
const exists = (f) => fs.existsSync(path.join(ROOT, 'data', f));
const entities = read('entities.json');
const allPrompts = read('prompts.json');
const packs = read('packs.json');
const taxa = exists('taxa.json') ? read('taxa.json') : {};

// ---- taxon fields live on the seeds (the source of truth for prompt wording); copy them onto the prompts
const seedsById = Object.fromEntries(read('prompt-seeds.json').map(s => [s.id, s]));
let taxonChanged = false;
for (const p of allPrompts) {
  const s = seedsById[p.id] || {};
  for (const k of ['taxon', 'taxonFilter']) {
    if (s[k] && p[k] !== s[k]) { p[k] = s[k]; taxonChanged = true; }
    if (!s[k] && p[k]) { delete p[k]; taxonChanged = true; }
  }
  if (p.taxon) for (const g of dive.taxonGroups(p.taxon)) if (!taxa[g]) console.warn('warn: prompt ' + p.id + ' names taxon group "' + g + '" which is not in data/taxa.json');
  if (p.taxonFilter) { try { new RegExp(p.taxonFilter, 'i'); } catch (e) { console.error('ERROR: prompt ' + p.id + ' has an invalid taxonFilter'); process.exit(1); } }
}
if (taxonChanged) fs.writeFileSync(path.join(ROOT, 'data', 'prompts.json'), JSON.stringify(allPrompts, null, 1) + '\n');
const prompts = allPrompts.filter(p => p.answers && p.answers.length);
const stamp = new Date().toISOString();
const header = '/* GENERATED by build.js on ' + stamp + ' — edit data/*.json and run `node build.js` instead. */\n';

// ---- illustrations: an entity gets art: true when data/illustrations/<id>.svg exists
const artDir = path.join(ROOT, 'data', 'illustrations');
const artIds = new Set(fs.existsSync(artDir) ? fs.readdirSync(artDir).filter(f => f.endsWith('.svg')).map(f => f.slice(0, -4)) : []);
for (const e of entities) { if (artIds.has(e.id)) e.art = true; else delete e.art; }

// ---- schedule: freeze every day up to today, regenerate the rest
const schedulePath = path.join(ROOT, 'data', 'schedule.json');
const existing = fs.existsSync(schedulePath) ? JSON.parse(fs.readFileSync(schedulePath, 'utf8')) : {};
const today = dive.dayKey(new Date());
let fromKey = dive.LAUNCH_DATE;
while (existing[fromKey] && fromKey <= today) fromKey = dive.keyPlusDays(fromKey, 1);
const toKey = dive.keyPlusDays(today, SCHEDULE_DAYS_AHEAD);
const schedule = dive.buildSchedule(prompts, existing, fromKey, toKey);
fs.writeFileSync(schedulePath, JSON.stringify(schedule, null, 0).replace(/\],"/g, '],\n"') + '\n');
const frozenDays = Object.keys(schedule).filter(k => k < fromKey).length;

const byId = {};
for (const e of entities) byId[e.id] = e;
const version = crypto.createHash('sha1').update(JSON.stringify(entities) + JSON.stringify(prompts) + JSON.stringify(schedule) + JSON.stringify(taxa)).digest('hex').slice(0, 12);
fs.writeFileSync(path.join(ROOT, 'data', 'version.json'), JSON.stringify({ version, built: stamp }) + '\n');
fs.writeFileSync(path.join(ROOT, 'entities.js'), header + 'window.FATHOM_ENTITIES = ' + JSON.stringify(byId) + ';\n');
fs.writeFileSync(path.join(ROOT, 'prompts.js'), header + 'window.FATHOM_PROMPTS = ' + JSON.stringify(prompts) + ';\nwindow.FATHOM_PACKS = ' + JSON.stringify(packs) + ';\nwindow.FATHOM_SCHEDULE = ' + JSON.stringify(schedule) + ';\nwindow.FATHOM_DATA_VERSION = ' + JSON.stringify(version) + ';\nwindow.FATHOM_DATA_BUILT = ' + JSON.stringify(stamp) + ';\n');
fs.writeFileSync(path.join(ROOT, 'taxa.js'), header + 'window.FATHOM_TAXA = ' + JSON.stringify(taxa) + ';\n');

// ---- boot bundle
const bootDays = {};
for (let i = 0; i < BOOT_DAYS; i++) { const k = dive.keyPlusDays(today, i); if (schedule[k]) bootDays[k] = schedule[k]; }
const bootPromptIds = new Set(TUTORIAL_PROMPT_IDS);
for (const ids of Object.values(bootDays)) ids.forEach(id => bootPromptIds.add(id));
const promptsById = dive.byId(prompts);
const bootPrompts = Array.from(bootPromptIds).map(id => promptsById[id]).filter(Boolean);
const bootEntities = {};
for (const p of bootPrompts) for (const a of p.answers) if (byId[a.entity]) bootEntities[a.entity] = byId[a.entity];
// only the names the boot prompts can actually accept travel in boot.js (the filters cut 23,000 fish to a few hundred)
const bootTaxa = {};
for (const p of bootPrompts) {
  if (!p.taxon) continue;
  const filter = p.taxonFilter ? new RegExp(p.taxonFilter, 'i') : null;
  for (const g of dive.taxonGroups(p.taxon)) {
    const names = (taxa[g] || []).filter(n => !filter || filter.test(dive.normalise(n)));
    bootTaxa[g] = Array.from(new Set((bootTaxa[g] || []).concat(names)));
  }
}
const boot = { built: stamp, version, days: Object.keys(bootDays), prompts: bootPrompts, entities: bootEntities, packs, schedule: bootDays, taxa: bootTaxa };
fs.writeFileSync(path.join(ROOT, 'boot.js'), header + 'window.FATHOM_SITE = ' + JSON.stringify({ siteUrl: SITE_URL }) + ';\nwindow.FATHOM_BOOT = ' + JSON.stringify(boot) + ';\nwindow.FATHOM_DATA_VERSION = ' + JSON.stringify(version) + ';\n');

// ---- site files that depend on the address: robots.txt, sitemap.xml, the Open Graph tags in index.html
const base = SITE_URL || '';
fs.writeFileSync(path.join(ROOT, 'robots.txt'), 'User-agent: *\nAllow: /\n' + (base ? 'Sitemap: ' + base + '/sitemap.xml\n' : ''));
const pages = ['', 'privacy.html', 'terms.html', 'refunds.html'];
fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + pages.map(p => '  <url><loc>' + (base || 'https://example.invalid') + '/' + p + '</loc><changefreq>' + (p ? 'monthly' : 'daily') + '</changefreq></url>').join('\n') + '\n</urlset>\n');
let html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const ogToday = fs.existsSync(path.join(ROOT, 'icons', 'og', today + '.png')) ? 'icons/og/' + today + '.png' : 'icons/og.png';
html = html.replace(/<meta property="og:image" content="[^"]*">/, '<meta property="og:image" content="' + (base ? base + '/' : '') + ogToday + '">');
html = html.replace(/<meta property="og:url" content="[^"]*">\n?/, '');
if (base) html = html.replace('<meta property="og:type" content="website">', '<meta property="og:type" content="website">\n  <meta property="og:url" content="' + base + '/">');
html = html.replace(/<link rel="canonical" href="[^"]*">\n?/, '');
if (base) html = html.replace('<link rel="manifest" href="manifest.json">', '<link rel="canonical" href="' + base + '/">\n  <link rel="manifest" href="manifest.json">');
fs.writeFileSync(path.join(ROOT, 'index.html'), html);

// ---- dist/: exactly the files the site needs, nothing from data/, tests/ or supabase/
if (wantDist) {
  const dist = path.join(ROOT, 'dist');
  fs.rmSync(dist, { recursive: true, force: true });
  fs.mkdirSync(dist, { recursive: true });
  const copy = (rel) => { const from = path.join(ROOT, rel); if (!fs.existsSync(from)) return; fs.mkdirSync(path.dirname(path.join(dist, rel)), { recursive: true }); fs.cpSync(from, path.join(dist, rel), { recursive: true }); };
  ['index.html', '404.html', 'styles.css', 'app.js', 'game.js', 'pages.js', 'storage.js', 'charts.js', 'online.js', 'monetise.js', 'achievements.js', 'share.js', 'surface.js', 'retain.js', 'social.js', 'admin.js', 'boot.js', 'entities.js', 'prompts.js', 'taxa.js', 'sw.js', 'manifest.json', 'robots.txt', 'sitemap.xml', 'privacy.html', 'terms.html', 'refunds.html', 'admin.html', 'shared/dive.js', 'fonts', 'icons', 'data/illustrations'].forEach(copy);
  for (const html of ['index.html', 'admin.html']) {
    for (const m of fs.readFileSync(path.join(ROOT, html), 'utf8').matchAll(/<script src="([^"]+)"/g)) {
      if (!fs.existsSync(path.join(dist, m[1]))) throw new Error(html + ' loads ' + m[1] + ' but it is not in the dist list');
    }
  }
  fs.writeFileSync(path.join(dist, '.nojekyll'), '');
  if (base) fs.writeFileSync(path.join(dist, 'CNAME'), new URL(base).host + '\n');
  console.log('dist/ written (' + fs.readdirSync(dist).length + ' entries' + (base ? ', CNAME ' + new URL(base).host : ', no CNAME: data/site.json has no siteUrl') + ')');
}

const kb = (f) => Math.round(fs.statSync(path.join(ROOT, f)).size / 1024) + ' KB';
console.log('taxon prompts: ' + prompts.filter(p => p.taxon).length + ' of ' + prompts.length + (taxonChanged ? ' (data/prompts.json updated from seeds)' : ''));
console.log('built entities.js (' + entities.length + ' entities, ' + artIds.size + ' illustrated, ' + kb('entities.js') + '), prompts.js (' + prompts.length + ' prompts, ' + packs.length + ' packs, ' + kb('prompts.js') + '), taxa.js (' + Object.keys(taxa).length + ' groups, ' + Object.values(taxa).reduce((n, l) => n + l.length, 0) + ' names, ' + kb('taxa.js') + '), boot.js (' + bootPrompts.length + ' prompts, ' + Object.keys(bootEntities).length + ' entities, ' + kb('boot.js') + ')');
console.log('schedule ' + Object.keys(schedule).length + ' days (' + frozenDays + ' frozen, regenerated from ' + fromKey + '); data version ' + version + (partial ? ' [partial]' : ''));
